def media_hashes(path: Path) -> dict[str, str]:
    with zipfile.ZipFile(path) as archive:
        return {
            name: hashlib.sha256(archive.read(name)).hexdigest()
            for name in archive.namelist()
            if name.startswith("word/media/")
        }


def replace_text(paragraph, value: str, *, bold: bool | None = None) -> None:
    for run in list(paragraph.runs):
        run._element.getparent().remove(run._element)
    run = paragraph.add_run(value)
    run.font.name = "Times New Roman"
    run._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
    run.font.size = Pt(14)
    if bold is not None:
        run.font.bold = bold


def replace_exact(document: Document, old: str, new: str, *, style: str | None = None) -> None:
    matches = [paragraph for paragraph in document.paragraphs if paragraph.text.strip() == old]
    if len(matches) != 1:
        raise RuntimeError(f"Ожидался один абзац: {old!r}; найдено: {len(matches)}")
    paragraph = matches[0]
    replace_text(paragraph, new, bold=style is not None and style.startswith("Heading"))
    if style is not None:
        paragraph.style = document.styles[style]


def set_cell_text(cell, value: str) -> None:
    cell.text = value
    for paragraph in cell.paragraphs:
        paragraph.alignment = WD_ALIGN_PARAGRAPH.LEFT
        for run in paragraph.runs:
            run.font.name = "Times New Roman"
            run._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
            run.font.size = Pt(12)


